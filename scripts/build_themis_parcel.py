#!/usr/bin/env python3
"""Crop the THEMIS nighttime infrared mosaic (Mars Odyssey) to the analysis parcel.

The app uses it as a QUALITATIVE warning layer: at night, loose material (sand, dust, fine
regolith) cools faster than rock and firm ground, so it looks darker in this mosaic. The values are
8-bit brightness (DN), NOT thermal inertia units, and each pixel averages 100 m × 100 m.

Source: MC-23 Aeolis nighttime IR controlled mosaic, CC0 (USGS Astrogeology, S3 COG). Only the
parcel window is read over HTTP.

Frame: same as the HiRISE DTM (Mars 2015 sphere, equirectangular, clon = 0), so the crop is made
in DTM coordinates; the app moves it by the DTM → scene shift, like the parcel outline. THEMIS
registration against the DTM is not measured; at 100 m/px a few tens of metres do not matter.

Output (small, versioned): app/src/thermal/themis_nir_parcel.json
  - dn: row-major 8-bit values, north to south; 0 = nodata
  - bbox_lonlat (pixel edges), width, height, pixel_m
  - stretch: [p2, p98] of the valid DN inside the crop (the app shows values relative to these)

Usage (from the repository root):
    .venv/bin/pip install numpy rasterio
    .venv/bin/python scripts/build_themis_parcel.py [--bbox W S E N]
"""
from __future__ import annotations

import argparse
import json
import math
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import rasterio
from rasterio.windows import Window

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "app" / "src" / "thermal" / "themis_nir_parcel.json"
URL = (
    "https://astrogeo-ard.s3.us-west-2.amazonaws.com/mars/mo/themis/controlled_mosaics/"
    "mc23_aeolis_nir/mc23_aeolis_nir.tif"
)
R_SPHERE = 3_396_190.0
# Parcel extent in DTM coordinates (app/src/terrain/parcel.ts).
PARCEL = (137.36, -4.85, 137.41, -4.80)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--bbox", nargs=4, type=float, default=PARCEL, metavar=("W", "S", "E", "N"))
    args = parser.parse_args()
    west, south, east, north = args.bbox

    with rasterio.open(URL) as src:
        t = src.transform
        assert abs(t.b) < 1e-9 and abs(t.d) < 1e-9, "rotated rasters are not supported"
        to_x = lambda lon: math.radians(lon) * R_SPHERE  # noqa: E731
        to_y = lambda lat: math.radians(lat) * R_SPHERE  # noqa: E731
        # Whole pixels that touch the bbox (snap outwards).
        col0 = math.floor((to_x(west) - t.c) / t.a)
        col1 = math.ceil((to_x(east) - t.c) / t.a)
        row0 = math.floor((to_y(north) - t.f) / t.e)
        row1 = math.ceil((to_y(south) - t.f) / t.e)
        window = Window(col0, row0, col1 - col0, row1 - row0)
        dn = src.read(1, window=window)
        nodata = src.nodata if src.nodata is not None else 0
        pixel_m = abs(t.a)
        x_left, y_top = t.c + col0 * t.a, t.f + row0 * t.e
        x_right, y_bottom = t.c + col1 * t.a, t.f + row1 * t.e

    to_deg = lambda m: math.degrees(m / R_SPHERE)  # noqa: E731
    valid = dn[dn != nodata]
    if valid.size == 0:
        raise SystemExit("No valid THEMIS pixels in the window")
    p2, p98 = (int(v) for v in np.percentile(valid, [2, 98]))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    out = {
        "_comment": "Generated by scripts/build_themis_parcel.py. Qualitative: 8-bit brightness, not thermal inertia.",
        "source": {
            "class": "termica",
            "mission": "Mars Odyssey",
            "instrument": "THEMIS",
            "product": "MC-23 Aeolis nighttime IR controlled mosaic (100 m/px, CC0)",
            "url": URL,
            "kind": "observado",
            "fetched_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        },
        "frame": "DTM (Mars 2015 sphere, equirectangular, clon = 0)",
        "bbox_lonlat": {
            "west": to_deg(x_left),
            "south": to_deg(y_bottom),
            "east": to_deg(x_right),
            "north": to_deg(y_top),
        },
        "pixel_m": pixel_m,
        "width": int(dn.shape[1]),
        "height": int(dn.shape[0]),
        "nodata": int(nodata),
        "stretch": [p2, p98],
        "dn": [int(v) for v in dn.ravel()],
    }
    OUT.write_text(json.dumps(out, separators=(",", ":")) + "\n")
    print(
        f"{dn.shape[1]}×{dn.shape[0]} px at {pixel_m:g} m, DN {int(valid.min())}–{int(valid.max())}, "
        f"stretch {p2}–{p98}, {dn.size - valid.size} nodata → {OUT.relative_to(ROOT)}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
