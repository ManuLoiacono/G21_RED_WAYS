#!/usr/bin/env python3
"""Backup of the REMS daily reports and Curiosity positions used by the app's environment layer.

The app reads both feeds live from the browser (CORS allowed). If a feed fails, it falls back to
this backup (CLAUDE.md D4: live APIs with the last valid response saved). The backup keeps only
the fields the app uses, in compact rows, so it stays small enough to version.

Sources (observed, MSL):
  REMS daily reports   https://mars.nasa.gov/rss/api/?feed=weather&category=msl&feedtype=json
  Rover positions      https://mars.nasa.gov/mmgis-maps/MSL/Layers/json/MSL_waypoints.json
                       (internal endpoint without a contract: a copy is kept for that reason)

Output: app/src/environment/rems_backup.json
  rems:      [sol, terrestrial_date, ls, min_temp, max_temp, pressure, uv, sunrise, sunset,
              min_gts_temp, max_gts_temp]  (strings as published; missing values stay "--")
  waypoints: [sol, lon, lat, elev_geoid]

Usage (standard library only):  python3 scripts/build_rems_backup.py
"""
from __future__ import annotations

import json
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "app" / "src" / "environment" / "rems_backup.json"
REMS_URL = "https://mars.nasa.gov/rss/api/?feed=weather&category=msl&feedtype=json"
WAYPOINTS_URL = "https://mars.nasa.gov/mmgis-maps/MSL/Layers/json/MSL_waypoints.json"
REMS_FIELDS = (
    "sol", "terrestrial_date", "ls", "min_temp", "max_temp", "pressure",
    "local_uv_irradiance_index", "sunrise", "sunset", "min_gts_temp", "max_gts_temp",
)


def fetch(url: str) -> dict:
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (compatible; marswalk-data-prep)"})
    with urllib.request.urlopen(req, timeout=120) as res:
        return json.load(res)


def main() -> int:
    soles = fetch(REMS_URL)["soles"]
    rems = sorted(([s.get(k, "--") for k in REMS_FIELDS] for s in soles), key=lambda r: int(r[0]))
    features = fetch(WAYPOINTS_URL)["features"]
    waypoints = sorted(
        (
            [f["properties"]["sol"], round(f["properties"]["lon"], 7), round(f["properties"]["lat"], 7),
             round(f["properties"]["elev_geoid"], 2)]
            for f in features
        ),
        key=lambda w: w[0],
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        json.dumps(
            {
                "_comment": "Generated by scripts/build_rems_backup.py. Fallback when the live feeds fail.",
                "fetched_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                "rems_url": REMS_URL,
                "waypoints_url": WAYPOINTS_URL,
                "rems_fields": list(REMS_FIELDS),
                "rems": rems,
                "waypoints": waypoints,
            },
            separators=(",", ":"),
        )
        + "\n"
    )
    print(f"{len(rems)} REMS soles ({rems[0][1]} – {rems[-1][1]}), {len(waypoints)} waypoints → {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
